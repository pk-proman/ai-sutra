// Writes api/config.local.php from GitHub secrets so passwords never live in the repository.
import { writeFileSync } from 'fs';
const out = process.argv[2];
const q = v => "'" + String(v).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const { SMTP_PASSWORD, ERPNEXT_API_KEY, ERPNEXT_API_SECRET } = process.env;
const parts = [];
if (SMTP_PASSWORD) parts.push(`    'smtp' => ['password' => ${q(SMTP_PASSWORD)}],`);
if (ERPNEXT_API_KEY || ERPNEXT_API_SECRET) parts.push(`    'erpnext' => [${ERPNEXT_API_KEY ? `'api_key' => ${q(ERPNEXT_API_KEY)}, ` : ''}${ERPNEXT_API_SECRET ? `'api_secret' => ${q(ERPNEXT_API_SECRET)}` : ''}],`);
writeFileSync(out, `<?php\n// Generated by the deploy workflow from GitHub secrets. Do not edit or commit.\nreturn [\n${parts.join('\n')}\n];\n`, { mode: 0o640 });
